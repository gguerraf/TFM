"""
20_estimate_baseline_model.py
====================
Intra-ETF spillover model with endogenous shock definition.

The shock is the CAR of a constituent stock relative to a SECTOR benchmark
(not the market index), estimated via a rolling OLS market model.
Using a sector benchmark avoids the endogeneity problem of using the ETF
itself as benchmark for its own constituents.

SCOPE: XME and XLE only (validation run).
       Set VALIDATION_MODE = False to run all 5 ETFs.

KEY OPTIMIZATION: identify_shocks() is fully vectorized using numpy matrix
operations instead of a per-date loop. This reduces runtime from hours to
minutes for ETFs with ~30 constituents.

Inputs:
    processed/{etf}_holdings.csv   (from 01_load_holdings.py)
    processed/returns_clean.csv    (from 11_compute_returns.py)

Outputs:
    results/panel_full.csv
    results/regression_results.txt
    results/coef_plot.png
"""

