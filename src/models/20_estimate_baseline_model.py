def identify_shocks_vectorized(ret_stocks: pd.DataFrame,
                                ret_bench:  pd.Series) -> pd.DataFrame:
    """
    Identifies shock events for all constituent stocks using vectorized
    numpy operations instead of a per-date Python loop.

    Strategy:
        For each stock i, construct two matrices aligned on the returns index:
          Y : (T x 1) stock returns
          X : (T x 2) [ones, benchmark returns]

        Then use a rolling window approach:
          - For each eligible event date t0, the estimation window is
            rows [t0 - WINDOW - GAP : t0 - GAP]
          - The event window is rows [t0 : t0 + EVENT_H]

        Instead of looping over dates, we use stride tricks to batch all
        windows into a 3D array and solve all OLS systems at once via
        numpy.linalg.lstsq on the batch.

    Returns DataFrame with columns: t0, stock_i, car_i, is_negative
    """
    # Align benchmark to stock index
    bench = ret_bench.reindex(ret_stocks.index).fillna(0).values  # (T,)
    dates = ret_stocks.index
    T     = len(dates)
    records = []

    # Pre-build X matrix (same for all stocks): [ones, bench]
    X_full = np.column_stack([np.ones(T), bench])  # (T, 2)

    # Minimum index for event date
    min_event_idx = ESTIMATION_WINDOW + GAP
    max_event_idx = T - EVENT_H - 1

    if min_event_idx >= max_event_idx:
        print("  [WARN] Not enough data for shock identification.")
        return pd.DataFrame()

    n_events = max_event_idx - min_event_idx
    print(f"  Eligible event dates: {n_events:,}")

    # Build estimation window indices for all event dates at once
    # est_start[k] = k,  est_end[k] = k + ESTIMATION_WINDOW
    # event_start[k] = k + ESTIMATION_WINDOW + GAP
    event_indices = np.arange(min_event_idx, max_event_idx)  # (n_events,)

    # Estimation window: [event_idx - ESTIMATION_WINDOW - GAP,
    #                     event_idx - GAP)
    est_starts = event_indices - ESTIMATION_WINDOW - GAP   # may be negative
    est_ends   = event_indices - GAP

    # Keep only events where estimation window is fully within data
    valid_mask  = est_starts >= 0
    event_indices = event_indices[valid_mask]
    est_starts    = est_starts[valid_mask]
    est_ends      = est_ends[valid_mask]
    n_valid       = len(event_indices)

    print(f"  Valid event dates (full estimation window): {n_valid:,}")

    n_stocks = ret_stocks.shape[1]

    for s_idx, ticker in enumerate(ret_stocks.columns):
        if s_idx % 10 == 0:
            print(f"    Processing stock {s_idx+1}/{n_stocks}: {ticker}")

        y_full = ret_stocks[ticker].fillna(0).values  # (T,)

        # --- Vectorized OLS for all event dates ---
        # Build batched estimation windows: shape (n_valid, ESTIMATION_WINDOW, 2)
        # and corresponding y: shape (n_valid, ESTIMATION_WINDOW)
        #
        # We use a strided approach: for each event k, extract rows
        # est_starts[k] : est_ends[k] from X_full and y_full

        alphas = np.full(n_valid, np.nan)
        betas  = np.full(n_valid, np.nan)

        # Batch OLS using stride tricks for speed
        # Build index arrays for all windows simultaneously
        idx_matrix = (est_starts[:, None] +
                      np.arange(ESTIMATION_WINDOW)[None, :])  # (n_valid, W)

        Y_batch = y_full[idx_matrix]          # (n_valid, W)
        X_batch = X_full[idx_matrix]          # (n_valid, W, 2)

        # Solve all OLS systems at once using einsum (normal equations)
        # For each k: beta = (X'X)^{-1} X'y
        XtX = np.einsum('kij,kil->kjl', X_batch, X_batch)  # (n_valid, 2, 2)
        Xty = np.einsum('kij,ki->kj',   X_batch, Y_batch)  # (n_valid, 2)

        # Solve batch of 2x2 systems
        det  = XtX[:, 0, 0] * XtX[:, 1, 1] - XtX[:, 0, 1] * XtX[:, 1, 0]
        safe = np.abs(det) > 1e-12

        alphas[safe] = (XtX[safe, 1, 1] * Xty[safe, 0]
                        - XtX[safe, 0, 1] * Xty[safe, 1]) / det[safe]
        betas[safe]  = (XtX[safe, 0, 0] * Xty[safe, 1]
                        - XtX[safe, 1, 0] * Xty[safe, 0]) / det[safe]

        # --- Vectorized CAR computation ---
        # Event window: rows [event_idx : event_idx + EVENT_H + 1]
        ev_idx_matrix = (event_indices[:, None] +
                         np.arange(EVENT_H + 1)[None, :])  # (n_valid, H+1)

        # Clip to valid range
        ev_idx_matrix = np.clip(ev_idx_matrix, 0, T - 1)

        R_event  = y_full[ev_idx_matrix]         # (n_valid, H+1)
        Rm_event = bench[ev_idx_matrix]           # (n_valid, H+1)

        # AR_t = R_t - alpha - beta * Rm_t
        AR = (R_event
              - alphas[:, None]
              - betas[:, None] * Rm_event)        # (n_valid, H+1)

        CARs = AR.sum(axis=1)                     # (n_valid,)

        # --- Flag shocks ---
        valid_cars = CARs[~np.isnan(alphas)]
        if len(valid_cars) < 10:
            continue

        car_mean = np.nanmean(valid_cars)
        car_std  = np.nanstd(valid_cars)
        if car_std < 1e-10:
            continue

        for k in range(n_valid):
            if np.isnan(alphas[k]) or np.isnan(CARs[k]):
                continue
            if abs(CARs[k] - car_mean) > SHOCK_THRESHOLD * car_std:
                records.append({
                    "t0":          dates[event_indices[k]],
                    "stock_i":     ticker,
                    "car_i":       CARs[k],
                    "is_negative": int(CARs[k] < 0),
                })

    return pd.DataFrame(records)


